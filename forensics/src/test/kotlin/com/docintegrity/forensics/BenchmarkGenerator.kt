package com.docintegrity.forensics

import com.docintegrity.forensics.engine.ForensicReport
import com.docintegrity.forensics.engine.EngineInfo
import com.docintegrity.forensics.model.EvidenceClass
import com.docintegrity.forensics.model.Finding
import com.docintegrity.forensics.model.Verdict
import com.docintegrity.forensics.util.Json

/** Renders docs/BENCHMARK.md and docs/benchmark-results.json from live engine runs. No number here is typed in by hand. */
object BenchmarkGenerator {
    class Row(val s: Scenario, val none: ForensicReport, val with: ForensicReport?)
    class RefResult(val r: BenchmarkScenarios.RefRow, val report: ForensicReport)

    private fun first(t: String) = t.lineSequence().first().trim().let { if (it.length > 230) it.take(227) + "…" else it }
    private fun verdictCell(v: Verdict) = when (v) { Verdict.CONFIRMED_CHANGE -> "Confirmed change"; Verdict.SUSPICIOUS_INDICATORS -> "Suspicious indicators"; Verdict.NO_INDICATORS_DETECTED -> "No indicators detected"; Verdict.INCONCLUSIVE -> "Inconclusive" }

    private fun keyFindings(r: ForensicReport, max: Int = 4): List<Finding> =
        r.findings.filter { it.evidence == EvidenceClass.ESTABLISHED || it.evidence == EvidenceClass.INDICATOR }.take(max)

    fun markdown(rows: List<Row>, refs: List<RefResult>): String {
        val sb = StringBuilder()
        sb.appendLine("# Detection benchmark")
        sb.appendLine()
        sb.appendLine("_Generated by `BenchmarkTest` from real engine runs (ruleset `${EngineInfo.RULESET}`, engine ${EngineInfo.VERSION}). Do not edit by hand: `./gradlew :forensics:testDebugUnitTest --tests '*BenchmarkTest*' -Dbenchmark.write=true` regenerates it, and the test fails if this file drifts from the code._")
        sb.appendLine()
        sb.appendLine("## How to read this")
        sb.appendLine()
        sb.appendLine("* Every file below was made by a **real tool** (LibreOffice round trips, PyMuPDF edits, Pillow/img2pdf scans, pyHanko signatures); none is a hand-faked artefact. The generators are in `tools/fixtures/`.")
        sb.appendLine("* **Ground truth** is known because the author made the alteration. *Without original* = the file alone (no reference supplied). *With original* = the trusted original supplied as reference.")
        sb.appendLine("* A file counts as **flagged** when its report category is *Confirmed change* or *Suspicious indicators*. TP/FP/TN/FN are computed against ground truth at that level.")
        sb.appendLine("* **Sample size is tiny and constructed by the author.** These are demonstrations of what each mechanism can and cannot see, not accuracy statistics. No percentages are given because none would be calibrated.")
        sb.appendLine("* **Microsoft Word was not available.** Scenarios B–E use LibreOffice (import PDF → .docx → export PDF) as the word-processor stand-in. Word-specific tool labels are tested at string level only.")
        sb.appendLine()
        sb.appendLine("## Summary")
        sb.appendLine()
        sb.appendLine("| # | Scenario | Ground truth | Without original | | With trusted original | |")
        sb.appendLine("|---|----------|--------------|------------------|---|----------------------|---|")
        for (r in rows) {
            val a = BenchmarkScenarios.outcome(r.s.truth, r.none.verdict.verdict)
            val b = r.with?.let { BenchmarkScenarios.outcome(r.s.truth, it.verdict.verdict) }
            sb.appendLine("| ${r.s.id} | ${r.s.what} | ${r.s.truth.label} | ${verdictCell(r.none.verdict.verdict)} | **$a** | ${r.with?.let { verdictCell(it.verdict.verdict) } ?: "—"} | ${b?.let { "**$it**" } ?: ""} |")
        }
        sb.appendLine()
        fun tally(f: (Row) -> String?): String {
            val m = rows.mapNotNull(f).groupingBy { it }.eachCount()
            return listOf("TP", "FN", "TN", "FP").joinToString(", ") { "$it ${m[it] ?: 0}" }
        }
        sb.appendLine("**Counts (not rates):** without original — ${tally { BenchmarkScenarios.outcome(it.s.truth, it.none.verdict.verdict) }}; with trusted original — ${tally { r -> r.with?.let { BenchmarkScenarios.outcome(r.s.truth, it.verdict.verdict) } }}.")
        sb.appendLine()
        sb.appendLine("**What the pattern shows.** Without an original the engine detects edits that leave *structural* evidence (kept revision history, covered text, overlays on scans, broken or post-signature changes, grain-free patches) and misses edits that leave none (a name or amount changed in a Word round trip, a regenerated PDF, a same-quality re-saved scan, a valid signature over false content). Supplying a trusted original converts those misses into located, confirmed differences, and never turns a harmless re-export into a confirmed change.")
        sb.appendLine()
        sb.appendLine("## Scenarios")
        for (r in rows) {
            sb.appendLine()
            sb.appendLine("### ${r.s.id} — `${r.s.file}`")
            sb.appendLine()
            sb.appendLine("${r.s.what} *(Ground truth: ${r.s.truth.label}.)*")
            sb.appendLine()
            sb.appendLine("**Without original** → **${verdictCell(r.none.verdict.verdict)}** (${BenchmarkScenarios.outcome(r.s.truth, r.none.verdict.verdict)})")
            val kf = keyFindings(r.none)
            if (kf.isEmpty()) {
                sb.appendLine()
                sb.appendLine("* *Evidence detected:* no established evidence or indicator. Informational: " + (r.none.findings.filter { it.evidence == EvidenceClass.INFO }.take(3).joinToString("; ") { it.title }.ifEmpty { "—" }) + ".")
                val lim = r.none.findings.filter { it.evidence == EvidenceClass.LIMITATION && !it.id.startsWith("CMP_NO_REF") }
                if (lim.isNotEmpty()) sb.appendLine("* *Limitations stated:* " + lim.joinToString("; ") { it.title })
            } else {
                sb.appendLine()
                for (f in kf) {
                    sb.appendLine("* *Evidence detected* [${f.evidence.label}] **${f.title}** — ${first(f.detected)}")
                    sb.appendLine("  * *Establishes:* ${first(f.establishes)}")
                    sb.appendLine("  * *Unknown:* ${first(f.unknown)}")
                }
            }
            if (r.with != null) {
                sb.appendLine()
                sb.appendLine("**With trusted original (`${r.s.reference}`)** → **${verdictCell(r.with.verdict.verdict)}** (${BenchmarkScenarios.outcome(r.s.truth, r.with.verdict.verdict)})")
                val c = r.with.comparison
                if (c != null) sb.appendLine("* File bytes: ${c.bytesIdentical.name.lowercase()}; document meaning changed: ${c.meaningChanged.name.lowercase()}.")
                for (f in r.with.findings.filter { it.area == com.docintegrity.forensics.model.Area.COMPARISON && it.evidence != EvidenceClass.LIMITATION }.take(4)) {
                    sb.appendLine("* [${f.evidence.label}] **${f.title}** — ${first(f.detected)}")
                }
                val improved = BenchmarkScenarios.outcome(r.s.truth, r.none.verdict.verdict) != BenchmarkScenarios.outcome(r.s.truth, r.with.verdict.verdict)
                sb.appendLine("* *Original comparison improves the result:* **${if (improved) "yes" else "no change in outcome"}**.")
            }
            sb.appendLine()
            sb.appendLine("> **Assessment.** ${r.s.note}")
        }
        sb.appendLine()
        sb.appendLine("## J — other trusted references")
        sb.appendLine()
        sb.appendLine("| # | Comparison | Ground truth | Result | Outcome |")
        sb.appendLine("|---|------------|--------------|--------|---------|")
        for (x in refs) sb.appendLine("| ${x.r.id} | ${x.r.title} | ${x.r.truth.label} | ${verdictCell(x.report.verdict.verdict)} | **${BenchmarkScenarios.outcome(x.r.truth, x.report.verdict.verdict)}** |")
        sb.appendLine()
        for (x in refs) {
            sb.appendLine("* **${x.r.id}** — ${x.r.note}")
            for (f in x.report.findings.filter { it.area == com.docintegrity.forensics.model.Area.COMPARISON && it.evidence != EvidenceClass.LIMITATION }.take(2)) sb.appendLine("  * [${f.evidence.label}] ${f.title}: ${first(f.detected)}")
        }
        sb.appendLine()
        sb.appendLine("## Cases the engine does not support")
        sb.appendLine()
        for (u in UNSUPPORTED) sb.appendLine("* $u")
        sb.appendLine()
        sb.appendLine("## Evaluated and rejected")
        sb.appendLine()
        sb.appendLine("* **Error-level analysis (ELA).** Implemented with detail-stratified baselines and agreement across three re-encode qualities, then evaluated on the scan fixtures: it flagged 28–34 regions on *every* scan, including unedited controls, so it carried no discriminating information. It was removed rather than shipped as an indicator that cries wolf.")
        sb.appendLine("* **Noise analysis grid size.** The first version used 32 px blocks and missed the small flat patch in `Gh`; it was changed to 16 px after inspecting that file. Because the parameter was adjusted after looking at one edited fixture, the false-positive rate of the noise check is only checked on a handful of unedited controls (`G0`, `Gh0`, `Gn0`, the photographs) and is otherwise unmeasured.")
        return sb.toString()
    }

    val UNSUPPORTED = listOf(
        "**Proving a PDF→Word→PDF round trip.** Nothing in the output file reliably records it; only tool labels (informational) can hint at it. Without a trusted original, content changes made this way cannot be detected (scenarios C, D).",
        "**Recovering history from a fully regenerated or rewritten PDF** (scenarios Fb, I): the history does not exist in the file. This is reported as *unavailable*, never as *no tampering*.",
        "**Judging truth.** Neither a valid signature, a matching hash, a matching issuer record nor an absence of indicators shows that information in a document is true.",
        "**OCR / text comparison of scans.** Scanned pages are compared only as rendered pictures (indicators), never as text.",
        "**Double-JPEG / DCT-coefficient analysis, JPEG block-grid misalignment, resampling detection, clone-detection and machine-learning forgery detectors.** Not implemented; image checks are limited to those listed above.",
        "**Online certificate revocation.** The app has no network permission. Revocation is evaluated only from CRL/OCSP data embedded in the file or the signature; otherwise it is reported *unknown*.",
        "**Legacy `adbe.x509.rsa_sha1` signatures and algorithms the platform cannot process** are reported as *could not be verified*, not as valid or invalid.",
        "**Trust lists used for PDFs in practice (Adobe AATL, EU trusted lists).** Only the device's certificate store (or a test CA in tests) is used, so legitimate signatures can show as *unknown root*.",
        "**Encrypted PDFs.** Structure is examined; strings, metadata and streams are not. Reported as a limitation.",
        "**Vertical or rotated text, and multi-column reading order,** in word reconstruction. Comparisons are consistent between two files extracted the same way but can differ across very different layouts.",
        "**DOCX originals as visual references.** A .docx can be compared by text, entities and embedded pictures, not by rendered pages.",
        "**Running on a physical device or emulator.** The APK is built and its UI is exercised by Robolectric tests, but no emulator was available in the build environment; `PdfRenderer` page rendering was not executed on Android (the visual-comparison algorithm itself is tested with a `pdftoppm` renderer).",
    )

    fun json(rows: List<Row>, refs: List<RefResult>): String = Json.obj {
        str("ruleset", EngineInfo.RULESET); str("engine", EngineInfo.VERSION)
        arr("scenarios", rows) { r ->
            str("id", r.s.id); str("file", r.s.file); str("truth", r.s.truth.name)
            str("without_original", r.none.verdict.verdict.name); str("without_original_outcome", BenchmarkScenarios.outcome(r.s.truth, r.none.verdict.verdict))
            strs("without_original_findings", r.none.findings.filter { it.evidence != EvidenceClass.INFO }.map { "${it.evidence.name}:${it.id}" })
            str("with_original", r.with?.verdict?.verdict?.name); str("with_original_outcome", r.with?.let { BenchmarkScenarios.outcome(r.s.truth, it.verdict.verdict) })
            strs("with_original_findings", r.with?.findings?.filter { it.evidence != EvidenceClass.INFO }?.map { "${it.evidence.name}:${it.id}" } ?: emptyList())
        }
        arr("reference_variants", refs) { x ->
            str("id", x.r.id); str("file", x.r.file); str("truth", x.r.truth.name); str("result", x.report.verdict.verdict.name)
            str("outcome", BenchmarkScenarios.outcome(x.r.truth, x.report.verdict.verdict))
        }
        strs("unsupported", UNSUPPORTED)
    }
}
