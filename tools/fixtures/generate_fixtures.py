#!/usr/bin/env python3
"""
Generates the forensic benchmark fixtures from REAL tools (no hand-faked artefacts).

Requirements (outside the Android build): LibreOffice (soffice), poppler (pdftoppm), and the Python packages
  pymupdf pillow reportlab img2pdf python-docx numpy
Optional (signature fixtures, see generate_signed.py): pyhanko

Usage:  python3 generate_fixtures.py --out forensics/src/test/resources/fixtures --work /tmp/fxwork

Scenario map (see docs/BENCHMARK.md):
  A   original PDF, no edits                       (ReportLab; Creator "anonymous")
  B   A -> DOCX -> PDF, unchanged                  (LibreOffice import + export)
  C   A -> DOCX -> name altered -> PDF
  D   A -> DOCX -> amount altered -> PDF
  E   legitimate document authored as DOCX -> PDF  (python-docx authored, LibreOffice export;
                                                    Microsoft Word is not available in this environment)
  F   A edited directly with a PDF editor library, saved as an INCREMENTAL update (PyMuPDF)
  Fb  same edit, saved as a FULL rewrite (what "Save As" / optimise does)
  G*  scan family: see generate_scans.py
  I   F fully regenerated by LibreOffice Draw (no revision history survives)
  K   A with the embedded photograph swapped (for photo comparison)
  N1  control: browser-printed receipt (Chromium Skia/PDF) - different generator, same content
"""
import argparse
import os
import random
import shutil
import subprocess
import sys
import zipfile

import fitz  # PyMuPDF
import img2pdf
from PIL import Image, ImageDraw, ImageFilter, ImageFont
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

NAME_OLD, NAME_NEW = "John Mwansa", "Joseph Mwanza"
AMT_OLD, AMT_NEW = "4,250.00", "42,500.00"


def run(cmd, **kw):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, **kw)
    if r.returncode != 0:
        print(r.stdout)
        raise SystemExit(f"command failed: {cmd}")
    return r.stdout


def photo(path, palette, variant=1):
    """Deterministic synthetic 'portrait' (gradient + head + shoulders + noise), saved as JPEG."""
    rnd = random.Random(sum(palette))
    w, h = 160, 200
    im = Image.new("RGB", (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            g = int(60 + 120 * y / h)
            px[x, y] = (g * palette[0] // 255, g * palette[1] // 255, g * palette[2] // 255)
    d = ImageDraw.Draw(im)
    if variant == 1:
        d.ellipse((50, 30, 110, 105), fill=(210, 170, 140))
        d.ellipse((15, 110, 145, 260), fill=(40, 50, 90))
    else:  # a different person: head higher/larger, narrower shoulders, hair block
        d.rectangle((38, 12, 128, 62), fill=(30, 25, 20))
        d.ellipse((38, 24, 128, 122), fill=(190, 140, 110))
        d.ellipse((40, 128, 120, 260), fill=(110, 40, 40))
    for _ in range(4000):
        x, y = rnd.randrange(w), rnd.randrange(h)
        r, g, b = px[x, y]
        n = rnd.randint(-12, 12)
        px[x, y] = (max(0, min(255, r + n)), max(0, min(255, g + n)), max(0, min(255, b + n)))
    im = im.filter(ImageFilter.GaussianBlur(0.6))
    im.save(path, "JPEG", quality=88)


def make_original(path, photo_path):
    c = canvas.Canvas(path, pagesize=A4, invariant=1)
    c.setTitle("Payment receipt")
    c.setAuthor("Finance Office")
    w, h = A4
    c.setFont("Helvetica-Bold", 20)
    c.drawString(72, h - 90, "PAYMENT RECEIPT")
    c.drawImage(photo_path, w - 72 - 80, h - 140, width=80, height=100)
    c.setFont("Helvetica", 12)
    y = h - 130
    for line in [
        "Receipt No: RC-2024-004217",
        "Date of issue: 12 March 2024",
        f"Received from: {NAME_OLD}",
        "Payment reference: INV-77831",
        "Received by: Grace Banda, Finance Officer",
    ]:
        c.drawString(72, y, line)
        y -= 22
    c.drawString(72, y - 10, "Description")
    c.drawString(360, y - 10, "Qty")
    c.drawString(440, y - 10, "Amount")
    y -= 34
    for d, q, a in [("Tuition fee", "1", "ZMW 4,000.00"), ("Registration fee", "1", "ZMW 250.00")]:
        c.drawString(72, y, d)
        c.drawString(360, y, q)
        c.drawString(440, y, a)
        y -= 20
    c.setFont("Helvetica-Bold", 12)
    c.drawString(72, y - 10, "Total received")
    c.drawString(440, y - 10, f"ZMW {AMT_OLD}")
    c.save()


def lo(args, outdir):
    os.makedirs(outdir, exist_ok=True)
    return run(["soffice", "--headless", "--norestore"] + args + ["--outdir", outdir], timeout=240)


def pdf_to_docx(pdf, outdir):
    lo(["--infilter=writer_pdf_import", "--convert-to", "docx:MS Word 2007 XML", pdf], outdir)
    return os.path.join(outdir, os.path.splitext(os.path.basename(pdf))[0] + ".docx")


def docx_to_pdf(docx, outdir):
    lo(["--convert-to", "pdf", docx], outdir)
    return os.path.join(outdir, os.path.splitext(os.path.basename(docx))[0] + ".pdf")


def docx_replace(src, dst, old, new):
    """Edit text inside word/document.xml of a DOCX (what a person does in Word, done at the XML level)."""
    zin = zipfile.ZipFile(src)
    zout = zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED)
    hit = 0
    for item in zin.infolist():
        data = zin.read(item.filename)
        if item.filename == "word/document.xml":
            s = data.decode("utf-8")
            hit = s.count(old)
            s = s.replace(old, new)
            data = s.encode("utf-8")
        zout.writestr(item, data)
    zout.close()
    if hit == 0:
        raise SystemExit(f"text {old!r} not found as a single run inside {src}")


def roundtrip(a_pdf, work, tag, edit=None):
    d = os.path.join(work, "rt_" + tag)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    src = os.path.join(d, tag + ".pdf")
    shutil.copy(a_pdf, src)
    docx = pdf_to_docx(src, d)
    if edit:
        edited = os.path.join(d, tag + "_edited.docx")
        docx_replace(docx, edited, *edit)
        os.replace(edited, docx)
    out = os.path.join(d, "out")
    return docx_to_pdf(docx, out)


def make_docx_native(path):
    import docx
    doc = docx.Document()
    doc.core_properties.author = "Finance Office"
    doc.core_properties.title = "Payment receipt"
    p = doc.add_paragraph()
    r = p.add_run("PAYMENT RECEIPT")
    r.bold = True
    for line in [
        "Receipt No: RC-2024-004217",
        "Date of issue: 12 March 2024",
        f"Received from: {NAME_OLD}",
        "Payment reference: INV-77831",
        "Received by: Grace Banda, Finance Officer",
        "Tuition fee 1 ZMW 4,000.00",
        "Registration fee 1 ZMW 250.00",
        f"Total received ZMW {AMT_OLD}",
    ]:
        doc.add_paragraph(line)
    doc.save(path)


def edit_with_editor(src, dst, incremental):
    """Replace the name using redaction + inserted text, as a PDF editor does."""
    shutil.copy(src, dst)
    doc = fitz.open(dst)
    page = doc[0]
    hits = page.search_for(NAME_OLD)
    if not hits:
        raise SystemExit("name not found for editing")
    r = hits[0]
    page.add_redact_annot(fitz.Rect(r.x0 - 1, r.y0 - 1, r.x1 + 2, r.y1 + 1), fill=(1, 1, 1))
    page.apply_redactions()
    page.insert_text((r.x0, r.y1 - 2.7), NAME_NEW, fontname="helv", fontsize=12)
    if incremental:
        doc.saveIncr()
    else:
        tmp = dst + ".tmp"
        doc.save(tmp, garbage=4, deflate=True, clean=True)
        doc.close()
        os.replace(tmp, dst)
        return
    doc.close()


def render_png(pdf, png_base, dpi=200):
    run(["pdftoppm", "-r", str(dpi), "-png", "-singlefile", pdf, png_base])
    return png_base + ".png"


def make_scan(pdf, out_jpg, quality=75):
    png = render_png(pdf, out_jpg[:-4] + "_raw")
    im = Image.open(png).convert("RGB")
    rnd = random.Random(7)
    px = im.load()
    for _ in range(im.width * im.height // 60):
        x, y = rnd.randrange(im.width), rnd.randrange(im.height)
        r, g, b = px[x, y]
        n = rnd.randint(-8, 8)
        px[x, y] = (max(0, min(255, r + n)), max(0, min(255, g + n)), max(0, min(255, b + n)))
    im = im.rotate(0.35, resample=Image.BICUBIC, fillcolor=(250, 250, 250))
    im = im.filter(ImageFilter.GaussianBlur(0.5))
    im.save(out_jpg, "JPEG", quality=quality)
    return out_jpg


def edit_scan(src_jpg, dst_jpg, quality, pdf_for_geometry):
    im = Image.open(src_jpg).convert("RGB")
    doc = fitz.open(pdf_for_geometry)
    hits = doc[0].search_for("ZMW " + AMT_OLD)
    r = hits[0]
    s = 200 / 72
    box = (int(r.x0 * s) - 6, int(r.y0 * s) - 4, int(r.x1 * s) + 70, int(r.y1 * s) + 4)
    d = ImageDraw.Draw(im)
    d.rectangle(box, fill=(250, 250, 250))
    font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", int((r.y1 - r.y0) * s * 0.85))
    d.text((box[0] + 6, box[1] + 2), "ZMW " + AMT_NEW, fill=(20, 20, 20), font=font)
    im.save(dst_jpg, "JPEG", quality=quality)


def jpg_to_pdf(jpg, pdf):
    with open(pdf, "wb") as f:
        f.write(img2pdf.convert(jpg, layout_fun=img2pdf.get_layout_fun((img2pdf.mm_to_pt(210), img2pdf.mm_to_pt(297)))))


def chromium_receipt(path, work):
    html = os.path.join(work, "n1.html")
    with open(html, "w") as f:
        f.write(f"""<html><body style="font-family:Arial;margin:72px"><h2>PAYMENT RECEIPT</h2>
<p>Receipt No: RC-2024-004217<br>Date of issue: 12 March 2024<br>Received from: {NAME_OLD}<br>
Payment reference: INV-77831<br>Received by: Grace Banda, Finance Officer</p>
<p>Tuition fee 1 ZMW 4,000.00<br>Registration fee 1 ZMW 250.00</p><p><b>Total received ZMW {AMT_OLD}</b></p></body></html>""")
    js = os.path.join(work, "n1.js")
    with open(js, "w") as f:
        f.write(f"""const {{chromium}}=require('playwright');(async()=>{{const b=await chromium.launch();const p=await b.newPage();
await p.goto('file://{html}');await p.pdf({{path:'{path}',format:'A4'}});await b.close();}})();""")
    env = dict(os.environ)
    env.setdefault("NODE_PATH", subprocess.run(["npm", "root", "-g"], stdout=subprocess.PIPE, text=True).stdout.strip())
    run(["node", js], env=env, timeout=120)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--work", required=True)
    a = ap.parse_args()
    out, work = os.path.abspath(a.out), os.path.abspath(a.work)
    os.makedirs(out, exist_ok=True)
    os.makedirs(work, exist_ok=True)

    p1, p2 = os.path.join(work, "photo1.jpg"), os.path.join(work, "photo2.jpg")
    photo(p1, (255, 220, 190))
    photo(p2, (190, 230, 255), variant=2)

    A = os.path.join(out, "A_original.pdf")
    make_original(A, p1)
    K = os.path.join(out, "K_photo_swapped.pdf")
    make_original(K, p2)

    shutil.copy(roundtrip(A, work, "B"), os.path.join(out, "B_roundtrip_unchanged.pdf"))
    shutil.copy(roundtrip(A, work, "C", (NAME_OLD, NAME_NEW)), os.path.join(out, "C_roundtrip_name_altered.pdf"))
    shutil.copy(roundtrip(A, work, "D", (f"ZMW {AMT_OLD}", f"ZMW {AMT_NEW}")), os.path.join(out, "D_roundtrip_amount_altered.pdf"))

    e_docx = os.path.join(work, "E_native.docx")
    make_docx_native(e_docx)
    shutil.copy(docx_to_pdf(e_docx, os.path.join(work, "E_out")), os.path.join(out, "E_native_docx_export.pdf"))
    shutil.copy(e_docx, os.path.join(out, "E_source.docx"))   # the authored original, usable as a DOCX reference

    F = os.path.join(out, "F_editor_incremental.pdf")
    edit_with_editor(A, F, incremental=True)
    Fb = os.path.join(out, "Fb_editor_full_rewrite.pdf")
    edit_with_editor(A, Fb, incremental=False)

    # scans (G0, G, Gb, Gp, Gs, Gn0, Gn) are produced by generate_scans.py from A_original.pdf

    # I: regenerate F entirely (LibreOffice Draw opens the PDF and exports a brand-new file)
    idir = os.path.join(work, "I_out")
    shutil.rmtree(idir, ignore_errors=True)
    shutil.copy(F, os.path.join(work, "I_src.pdf"))
    lo(["--convert-to", "pdf:draw_pdf_Export", os.path.join(work, "I_src.pdf")], idir)
    shutil.copy(os.path.join(idir, "I_src.pdf"), os.path.join(out, "I_regenerated_no_history.pdf"))

    try:
        chromium_receipt(os.path.join(out, "N1_control_browser_print.pdf"), work)
    except SystemExit as e:
        print("WARNING: skipped N1 control:", e)

    print("fixtures written to", out)
    for f in sorted(os.listdir(out)):
        print(f"  {f}  {os.path.getsize(os.path.join(out, f))} bytes")


if __name__ == "__main__":
    sys.exit(main())
